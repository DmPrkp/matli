/**
 * Сборка кода варианта — единственное место, где живёт это правило.
 *
 * code = id_позиции[:id_значения_параметра]…
 *   '8:207:226' — материал 8, Ø 8 мм (параметр 207), длина 50 мм (параметр 226)
 *   '7'         — позиция без типоразмеров: параметров нет, код вырождается в id
 *
 * Используется и сервисом при создании через API, и сидами. В самих данных
 * код не хранится: в исходном справочнике его вбивали руками, и он успел
 * разойтись с параметрами в трёх вариантах из двухсот.
 *
 * Порядок: id значений сортируются по возрастанию. В исходных сидах порядок был
 * смысловым (сначала Ø, потом длина), но на текущих данных это одно и то же —
 * id диаметров меньше id длин. Сортировка вдобавок делает код детерминированным:
 * иначе один и тот же набор параметров в разном порядке дал бы разные коды
 * и породил дубли вариантов.
 */
export function buildVariantCode(ownerId: number, paramValueIds: readonly number[]): string {
  return [ownerId, ...[...paramValueIds].sort((a, b) => a - b)].join(':');
}
